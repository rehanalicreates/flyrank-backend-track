# BE-06: the LLM triage call as a background job
# ---------------------------------------------------------------------------

def _bg_worker(request: Request) -> JobWorker:
    """The worker pool belongs to the current app's lifespan (loop-bound queue)."""
    worker = getattr(request.app.state, "bg_worker", None)
    if worker is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"error": "workers_not_running", "message": "Worker pool is unavailable."},
        )
    return worker


@app.post(
    "/jobs/triage",
    response_model=JobAccepted,
    status_code=status.HTTP_202_ACCEPTED,
    tags=["jobs"],
)
def create_triage_job(payload: TriageRequest, request: Request, response: Response) -> JobAccepted:
    """Accept fast, work in the background (BE-06).

    Answers 202 immediately with a job id; a background worker performs the
    LLM triage call and stores the result. Poll GET /jobs/triage/{job_id} for
    the outcome. A repeated idempotency_key returns the SAME job instead of
    creating a duplicate (idempotency). Input validation still returns 400
    naming the field."""
    if payload.idempotency_key:
        existing = bg_store.find_by_idempotency_key(payload.idempotency_key)
        if existing is not None:
            job_id = existing["job_id"]
            accepted = JobAccepted(
                job_id=job_id,
                status=existing["status"],
                status_url=f"/jobs/triage/{job_id}",
            )
            response.headers["Location"] = accepted.status_url
            return accepted

    job_id = f"triage_{uuid.uuid4().hex[:12]}"
    bg_store.create(job_id, payload.message, payload.idempotency_key)
    _bg_worker(request).enqueue(job_id)
    accepted = JobAccepted(job_id=job_id, status="queued", status_url=f"/jobs/triage/{job_id}")
    response.headers["Location"] = accepted.status_url
    return accepted


@app.get("/jobs/triage/{job_id}", response_model=JobResponse, tags=["jobs"])
def get_triage_job(job_id: str) -> JobResponse:
    """Status + result of one background job. 404 if the id is unknown."""
    job = bg_store.get(job_id)
    if job is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={"error": "job_not_found", "message": f"No job with id {job_id}."},
        )
    return JobResponse(**job)
