# Durable job store: process-wide, safe to share (thread-locked, append-only).
bg_store = JobStore()


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Start the worker pool with the API; drain it on shutdown.

    The pool is created HERE, inside the running event loop, because an
    asyncio.Queue binds itself to the loop it is first used on. A pool made
    at import time would be bound to the wrong loop and starve.

    Startup also re-enqueues jobs a previous process left unfinished
    (the "jobs run twice" case - safe, because a triage job is a pure
    function of its input message).
    """
    worker = JobWorker(bg_store, cfg=get_bg_settings())
    app.state.bg_worker = worker
    await worker.requeue_interrupted()
    tasks = [
        asyncio.create_task(worker.run())
        for _ in range(worker.cfg["worker_count"])
    ]
    yield
    for task in tasks:
        task.cancel()
    await asyncio.gather(*tasks, return_exceptions=True)

app = FastAPI(
    title="FlyRank Task API",
    description="Week 1 Backend AI Engineering assignment - a CRUD Task API with an LLM triage job (A17) executed on a background worker (BE-06).",
    version="1.0.0",
    lifespan=lifespan,
)


