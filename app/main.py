@app.exception_handler(TaskNotFoundError)
async def task_not_found_handler(request: Request, exc: TaskNotFoundError):
    return JSONResponse(
        status_code=status.HTTP_404_NOT_FOUND,
        content={"error": "task_not_found", "message": str(exc)},
    )


@app.exception_handler(RequestValidationError)
async def validation_error_handler(request: Request, exc: RequestValidationError):
    title_errors = ("missing", "value_error", "string_too_short")
    has_title_error = any(
        err.get("loc") == ("body", "title") and err.get("type") in title_errors
        for err in exc.errors()
    )
    if has_title_error:
        return JSONResponse(
            status_code=status.HTTP_400_BAD_REQUEST,
            content={
                "error": "validation_error",
                "message": "Title is required and must not be empty.",
            },
        )
    message_errors = ("missing", "value_error", "string_too_short", "string_too_long")
    has_message_error = any(
        err.get("loc") == ("body", "message") and err.get("type") in message_errors
        for err in exc.errors()
    )
    if has_message_error:
        return JSONResponse(
            status_code=status.HTTP_400_BAD_REQUEST,
            content={
                "error": "validation_error",
                "message": "'message' is required and must be a non-empty string.",
            },
        )
    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content={"detail": exc.errors()},
    )


